-- 로그인 기록: 누가 언제 로그인·로그아웃했는지 남긴다.
-- 기록은 두 경로로 쌓인다.
--   1) Supabase Auth(GoTrue)가 로그인 때 auth.sessions에 세션을 만들면 트리거가 'login' 행을 남긴다(주 경로).
--   2) 화면이 로그인 직후 log_login()을 부른다. 트리거가 이미 남겼으면(15초 안) 건너뛰고, 트리거를 만들지 못한
--      프로젝트에서는 이 호출이 기록을 남긴다(대비 경로). 로그아웃은 화면이 log_logout()으로 남긴다.
-- 로그인한 사용자(authenticated)는 기록을 읽기만 할 수 있다. 쓰기는 아래 security definer 함수만 한다.
-- security definer 함수는 마이그레이션을 실행한 롤(postgres)이 소유하므로 RLS를 거치지 않고 넣는다.
-- 이름을 잘못 해석할 틈이 없도록 definer 함수 안의 테이블·함수는 모두 스키마를 붙여 쓴다.

-- ===================================================================
-- 테이블
-- ===================================================================

create table public.login_logs (
  id          bigint generated by default as identity primary key,
  user_id     uuid,                                  -- 계정을 지워도 기록은 남기므로 외래 키를 걸지 않는다.
  email       text not null default '',
  login_id    text not null default '',              -- auth.users.raw_user_meta_data->>'login_id'(한글 아이디). 없으면 ''.
  event       text not null check (event in ('login', 'logout')),
  user_agent  text not null default '' check (char_length(user_agent) <= 500),
  ip          text not null default '' check (char_length(ip) <= 100),
  occurred_at timestamptz not null default now()
);

create index login_logs_occurred_at on public.login_logs (occurred_at desc);
create index login_logs_user_occurred_at on public.login_logs (user_id, occurred_at desc);

-- ===================================================================
-- 접근 권한: authenticated는 읽기만, anon은 아무것도 못 한다.
-- "새 테이블 자동 노출"이 켜진 프로젝트에서 기본 권한으로 붙은 쓰기 권한도 거둔다.
-- ===================================================================

alter table public.login_logs enable row level security;

create policy login_logs_authenticated_select on public.login_logs
  for select to authenticated using (true);

revoke all on table public.login_logs from public, anon, authenticated;
grant select on table public.login_logs to authenticated;
-- 행은 definer 함수(소유자 postgres)만 넣으므로 시퀀스 권한은 누구에게도 주지 않는다.
revoke all on sequence public.login_logs_id_seq from public, anon, authenticated;

-- ===================================================================
-- 함수
-- ===================================================================

-- 화면이 로그인 직후 부른다. 같은 사용자의 'login' 기록이 최근 15초 안에 있으면(트리거가 먼저 남김) 넣지 않는다.
-- 돌려주는 값: {"logged": true} 새로 남김, {"logged": false} 중복이라 건너뜀.
-- user_agent는 인자(화면의 navigator.userAgent)를 쓰고, 비어 있으면 요청 헤더의 User-Agent를 쓴다. 500자로 자른다.
-- ip는 PostgREST가 넘겨주는 요청 헤더에서 읽는다(없으면 '').
create function public.log_login(p_user_agent text default '') returns jsonb
language plpgsql volatile security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_email text;
  v_login_id text;
  v_headers jsonb;
  v_claims jsonb;
  v_ip text := '';
begin
  if v_uid is null then
    raise exception using message = '로그인이 필요합니다.', errcode = 'P0001';
  end if;

  -- 같은 사용자의 동시 호출이 둘 다 "중복 아님"으로 판정하지 않게 줄 세운다(트랜잭션이 끝나면 풀린다).
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('login_logs:' || v_uid::text));

  if exists (
    select from public.login_logs l
    where l.user_id = v_uid and l.event = 'login' and l.occurred_at > pg_catalog.now() - interval '15 seconds'
  ) then
    return jsonb_build_object('logged', false);
  end if;

  -- 요청 헤더·JWT 클레임은 PostgREST가 넣어 준다. 모양이 이상해도 기록은 남기도록 읽기 실패는 무시한다.
  begin
    v_headers := nullif(pg_catalog.current_setting('request.headers', true), '')::jsonb;
    v_claims := nullif(pg_catalog.current_setting('request.jwt.claims', true), '')::jsonb;
  exception when others then
    null;
  end;
  v_ip := coalesce(
    nullif(v_headers ->> 'cf-connecting-ip', ''),
    nullif(pg_catalog.btrim(pg_catalog.split_part(v_headers ->> 'x-forwarded-for', ',', 1)), ''),
    nullif(v_headers ->> 'x-real-ip', ''),
    '');

  -- auth.users를 읽지 못하는 환경이어도 JWT 클레임으로 채운다.
  begin
    select u.email, u.raw_user_meta_data ->> 'login_id' into v_email, v_login_id
    from auth.users u where u.id = v_uid;
  exception when others then
    null;
  end;

  insert into public.login_logs (user_id, email, login_id, event, user_agent, ip)
  values (
    v_uid,
    pg_catalog.left(coalesce(v_email, v_claims ->> 'email', ''), 320),
    pg_catalog.left(coalesce(v_login_id, v_claims #>> '{user_metadata,login_id}', ''), 200),
    'login',
    pg_catalog.left(coalesce(nullif(p_user_agent, ''), v_headers ->> 'user-agent', ''), 500),
    pg_catalog.left(v_ip, 100)
  );
  return jsonb_build_object('logged', true);
end
$$;

-- 화면이 로그아웃 직전에 부른다. 같은 사용자의 'logout' 기록이 최근 2초 안에 있으면(두 번 누름) 넣지 않는다.
-- 돌려주는 값은 log_login과 같다. user_agent·ip는 요청 헤더에서 읽는다.
create function public.log_logout() returns jsonb
language plpgsql volatile security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_email text;
  v_login_id text;
  v_headers jsonb;
  v_claims jsonb;
  v_ip text := '';
begin
  if v_uid is null then
    raise exception using message = '로그인이 필요합니다.', errcode = 'P0001';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('login_logs:' || v_uid::text));

  if exists (
    select from public.login_logs l
    where l.user_id = v_uid and l.event = 'logout' and l.occurred_at > pg_catalog.now() - interval '2 seconds'
  ) then
    return jsonb_build_object('logged', false);
  end if;

  begin
    v_headers := nullif(pg_catalog.current_setting('request.headers', true), '')::jsonb;
    v_claims := nullif(pg_catalog.current_setting('request.jwt.claims', true), '')::jsonb;
  exception when others then
    null;
  end;
  v_ip := coalesce(
    nullif(v_headers ->> 'cf-connecting-ip', ''),
    nullif(pg_catalog.btrim(pg_catalog.split_part(v_headers ->> 'x-forwarded-for', ',', 1)), ''),
    nullif(v_headers ->> 'x-real-ip', ''),
    '');

  begin
    select u.email, u.raw_user_meta_data ->> 'login_id' into v_email, v_login_id
    from auth.users u where u.id = v_uid;
  exception when others then
    null;
  end;

  insert into public.login_logs (user_id, email, login_id, event, user_agent, ip)
  values (
    v_uid,
    pg_catalog.left(coalesce(v_email, v_claims ->> 'email', ''), 320),
    pg_catalog.left(coalesce(v_login_id, v_claims #>> '{user_metadata,login_id}', ''), 200),
    'logout',
    pg_catalog.left(coalesce(v_headers ->> 'user-agent', ''), 500),
    pg_catalog.left(v_ip, 100)
  );
  return jsonb_build_object('logged', true);
end
$$;

-- 최근 기록부터 p_limit개(1~1000, 기본 200). RLS가 적용되도록 호출자 권한으로 읽는다.
-- 원소: {id, userId, email, loginId, event, userAgent, ip, occurredAt(UTC ISO 8601)}
create function public.list_login_logs(p_limit integer default 200) returns jsonb
language sql stable security invoker
set search_path = public
as $$
  select coalesce(jsonb_agg(
    jsonb_build_object(
      'id', l.id,
      'userId', l.user_id,
      'email', l.email,
      'loginId', l.login_id,
      'event', l.event,
      'userAgent', l.user_agent,
      'ip', l.ip,
      'occurredAt', public.iso_time(l.occurred_at)
    ) order by l.occurred_at desc, l.id desc), '[]'::jsonb)
  from (
    select * from public.login_logs
    order by occurred_at desc, id desc
    limit greatest(1, least(1000, coalesce(p_limit, 200)))
  ) l
$$;

-- auth.sessions 트리거 함수: 세션이 생기면(= 로그인) 'login' 행을 남긴다.
-- GoTrue 버전에 따라 user_agent·ip 칸이 없을 수 있으므로 to_jsonb로 읽는다(칸이 없으면 null).
-- 어떤 오류가 나도 로그인을 막으면 안 되므로 본문 전체에서 예외를 삼키고 항상 new를 돌려준다.
create function public.login_logs_on_session() returns trigger
language plpgsql volatile security definer
set search_path = public
as $$
declare
  v_row jsonb;
  v_email text;
  v_login_id text;
begin
  begin
    if new.user_id is not null then
      v_row := pg_catalog.to_jsonb(new);
      select u.email, u.raw_user_meta_data ->> 'login_id' into v_email, v_login_id
      from auth.users u where u.id = new.user_id;
      insert into public.login_logs (user_id, email, login_id, event, user_agent, ip)
      values (
        new.user_id,
        pg_catalog.left(coalesce(v_email, ''), 320),
        pg_catalog.left(coalesce(v_login_id, ''), 200),
        'login',
        pg_catalog.left(coalesce(v_row ->> 'user_agent', ''), 500),
        pg_catalog.left(coalesce(v_row ->> 'ip', ''), 100)
      );
    end if;
  exception when others then
    null;
  end;
  return new;
end
$$;

-- 함수 실행 권한: RPC 셋은 로그인한 사용자만. 트리거 함수는 GoTrue 롤(supabase_auth_admin)만.
revoke all on function
  public.log_login(text),
  public.log_logout(),
  public.list_login_logs(integer),
  public.login_logs_on_session()
from public, anon;
revoke all on function public.login_logs_on_session() from authenticated;

grant execute on function
  public.log_login(text),
  public.log_logout(),
  public.list_login_logs(integer)
to authenticated;

do $$
begin
  if exists (select from pg_catalog.pg_roles where rolname = 'supabase_auth_admin') then
    grant execute on function public.login_logs_on_session() to supabase_auth_admin;
  end if;
end
$$;

-- 트리거 만들기. auth 스키마 권한이 막힌 프로젝트에서도 마이그레이션(배포)이 실패하지 않도록 어떤 오류든 알림으로 바꾼다.
-- 트리거가 없으면 화면의 log_login()이 로그인 기록을 남긴다.
do $$
begin
  create trigger login_logs_on_session
  after insert on auth.sessions
  for each row execute function public.login_logs_on_session();
exception when others then
  raise notice 'auth.sessions 트리거를 만들지 못했습니다(%: %). 로그인 기록은 화면의 log_login()이 남깁니다.', sqlstate, sqlerrm;
end
$$;
